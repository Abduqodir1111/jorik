// Each emoji has one stable button/key, even when aliases overlap.
export const allEmoji = [
  ...new Map(
    emojiCategories.flatMap((c) =>
      c.items.map(([emoji, label]) => [emoji, { emoji, label }] as const),
    ),
  ).values(),
];
export function filterEmoji(query: string) {
  const q = query.trim().toLocaleLowerCase("ru").replace(/ё/g, "е");
  return allEmoji.filter((item) =>
    (item.emoji + " " + item.label).replace(/ё/g, "е").includes(q),
  );
}
export function insertEmoji(
  value: string,
  start: number,
  end: number,
  emoji: string,
) {
  const from = Math.max(0, Math.min(value.length, start));
  const to = Math.max(from, Math.min(value.length, end));
  return {
    text: value.slice(0, from) + emoji + value.slice(to),
    caret: from + emoji.length,
  };
}
